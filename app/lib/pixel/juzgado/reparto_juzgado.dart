/// Un personaje con sus tres fotogramas de reposo: quieto, respirando y parpadeando ([AnimacionPixel.reposo]).
/// [ms] es lo que dura cada respiración: con ritmos distintos, nadie respira a la vez que su vecino.
Sprite persona(String nombre, List<String> quieto, {int ms = 850}) =>
    Sprite.animado(nombre, [quieto, respirar(quieto), parpadear(quieto)], animacion: AnimacionPixel.reposo(ms: ms));

/// [filas] con la cabeza y los hombros un píxel más abajo: entra una fila vacía arriba y sale la primera fila del
/// cuerpo (desde [desde]) que es igual a la de debajo, así que no se nota que falta.
@visibleForTesting
List<String> respirar(List<String> filas, {int desde = 15}) {
  for (var y = desde; y < filas.length - 2; y++) {
    if (filas[y] == filas[y + 1]) {
      return ['.' * filas.first.length, ...filas.sublist(0, y), ...filas.sublist(y + 1)];
    }
  }
  return filas;
}

/// [filas] con los ojos cerrados: los píxeles de los ojos (la [fila] 9, columnas 8, 9, 14 y 15 en todas las cabezas
/// de este reparto) pasan a ser del color de la piel que tienen entre medias.
@visibleForTesting
List<String> parpadear(List<String> filas, {int fila = 9, List<int> columnas = const [8, 9, 14, 15]}) {
  final ojos = filas[fila];
  final piel = ojos.codeUnitAt(10);
  final cerrados = String.fromCharCodes([
    for (var x = 0; x < ojos.length; x++) columnas.contains(x) ? piel : ojos.codeUnitAt(x),
  ]);
  return retocar(filas, {fila: cerrados});
}

